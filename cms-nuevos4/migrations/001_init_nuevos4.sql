);

CREATE TABLE IF NOT EXISTS SITIOS (
  SLUG TEXT PRIMARY KEY,
  NOMBRE TEXT NOT NULL,
  TAGLINE TEXT,
  DOMINIO TEXT,
  FACEBOOK_ACTIVO INTEGER DEFAULT 1,
  FACEBOOK_PAGE_ID TEXT,
  FACEBOOK_TOKEN_SECRET TEXT,
  FACEBOOK_PAGE_TOKEN TEXT,
  FACEBOOK_TOKEN_UPDATED_AT TEXT
);

CREATE TABLE IF NOT EXISTS FB_TIMERS (
  SITE_SLUG TEXT PRIMARY KEY,
  LAST_POST_MS INTEGER DEFAULT 0,
  UPDATED_AT TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TICKER_HEADLINES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  TITULO TEXT NOT NULL,
  URL TEXT,
  FUENTE TEXT,
  FECHA_CREACION TEXT DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS FUENTES (
  ID INTEGER PRIMARY KEY AUTOINCREMENT,
  SITIO_SLUG TEXT NOT NULL,
  NOMBRE TEXT NOT NULL,
  URL TEXT NOT NULL,
  TIPO TEXT NOT NULL DEFAULT 'SCRAPING',
