CREATE TABLE IF NOT EXISTS DISTRIBUCION_ARTICULOS (
  ID TEXT PRIMARY KEY,
  ID_ARTICULO_FUENTE TEXT NOT NULL,
  ID_SITIO TEXT NOT NULL,
  ORDEN_PUBLICACION INTEGER,
  FECHA_PROGRAMADA TEXT,
  PUBLICADO INTEGER DEFAULT 0,
