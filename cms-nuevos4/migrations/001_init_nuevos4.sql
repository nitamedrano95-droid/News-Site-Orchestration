CREATE TABLE IF NOT EXISTS ARTICULOS_PARAFRASEADOS (
  ID TEXT PRIMARY KEY,
  TITULO_PARAFRASEADO TEXT NOT NULL,
  SLUG TEXT UNIQUE NOT NULL,
  CONTENIDO TEXT NOT NULL,
  DESCRIPCION_PARAFRASEADA TEXT,
  CATEGORIA TEXT DEFAULT 'NACIONAL',
  AUTOR TEXT DEFAULT 'NewsBot',
  FECHA_PUBLICACION TEXT DEFAULT CURRENT_TIMESTAMP,
  URL_IMAGEN TEXT,
  SOURCE_URL TEXT,
  ESTADO TEXT DEFAULT 'PUBLICADO',
  SITIO_DESTINO TEXT,
  CRIADO_EN TEXT DEFAULT CURRENT_TIMESTAMP,
  DESTACADO INTEGER DEFAULT 0,
  VISTAS INTEGER DEFAULT 0,
  FB_REQUERIDO INTEGER DEFAULT 0,
  FB_PUBLICADO INTEGER DEFAULT 0,
  FB_FECHA TEXT,
  FB_SITIOS_PUBLICADOS TEXT DEFAULT '',
  ES_BREVE INTEGER DEFAULT 0,
  ID_ARTICULO_ORIGINAL TEXT,
  LONGITUD INTEGER,
  VERIFICACION TEXT,
  VALIDO_AI INTEGER DEFAULT NULL,
  VALIDADO_EN TEXT DEFAULT NULL,
  RAZON_INVALIDO TEXT DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS ARTICULOS_ORIGINALES (
  ID TEXT PRIMARY KEY,
  URL TEXT,
