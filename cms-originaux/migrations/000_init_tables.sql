-- ARTICULOS_PARAFRASEADOS — Central article repository
CREATE TABLE IF NOT EXISTS ARTICULOS_PARAFRASEADOS (
  ID TEXT PRIMARY KEY,
  TITULO_PARAFRASEADO TEXT NOT NULL,
  SLUG TEXT UNIQUE NOT NULL,
  CONTENIDO TEXT NOT NULL,
  DESCRIPCION_PARAFRASEADA TEXT,
  CATEGORIA TEXT DEFAULT 'NACIONAL',
  AUTOR TEXT DEFAULT 'NewsBot',
  FECHA_PUBLICACION TEXT DEFAULT CURRENT_TIMESTAMP,
  URL_IMAGEN TEXT,
  SOURCE_URL TEXT,
  ESTADO TEXT DEFAULT 'PUBLICADO',
  SITIO_DESTINO TEXT,
  CRIADO_EN TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_articulos_slug ON ARTICULOS_PARAFRASEADOS(SLUG);
CREATE INDEX IF NOT EXISTS idx_articulos_fecha ON ARTICULOS_PARAFRASEADOS(FECHA_PUBLICACION);
CREATE INDEX IF NOT EXISTS idx_articulos_categoria ON ARTICULOS_PARAFRASEADOS(CATEGORIA);

